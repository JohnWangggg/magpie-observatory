#!/usr/bin/env node
// Syncs public/assets/views/manifest.js and docs/views-catalog.md
// with the views registered in public/assets/app.js (VIEW_META).
// Usage: node scripts/sync-views.mjs

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const app = readFileSync(join(root, "public/assets/app.js"), "utf8");

// --- extract VIEW_META entries ------------------------------------------------
const metaBlock = app.match(/VIEW_META\s*=\s*\[([\s\S]*?)\];/)[1];
const rows = [];
for (const m of metaBlock.matchAll(
  /\{\s*id:\s*"(\w+)"[\s\S]*?title:\s*"([^"]+)"[\s\S]*?eyebrow:\s*"([^"]*)"[\s\S]*?group:\s*"([^"]+)"[\s\S]*?hint:\s*"([^"]*)"/g
)) {
  rows.push({ id: m[1], title: m[2], eyebrow: m[3], group: m[4], hint: m[5] });
}
const ids = rows.map(r => r.id);
const groups = [];
const byGroup = {};
for (const r of rows) {
  if (!byGroup[r.group]) { byGroup[r.group] = []; groups.push(r.group); }
  byGroup[r.group].push(r);
}
// Built-in views live in app.js — no external views/{id}.js file; the manifest
// only drives modules registered via window.ObservatoryViews.
const BUILTIN = new Set(["route", "radar", "loom", "rhythm", "rings", "quota"]);

const viewFiles = readdirSync(join(root, "public/assets/views"))
  .filter(f => f.endsWith(".js") && f !== "manifest.js")
  .map(f => f.replace(/\.js$/, ""));
const viewFilesSet = new Set(viewFiles);
const metaSet = new Set(ids);

// keep VIEW_META order — builtins skipped for script loading but still in the
// manifest so the stage-view seeder makes their host divs.
const ordered = ids.concat(viewFiles.filter(v => !metaSet.has(v)));
const manifest =
  "// Auto-generated by scripts/sync-views.mjs — order matches VIEW_META.\n" +
  "// document.write at parser-time so view modules register into\n" +
  "// window.ObservatoryViews before app.js boots; stage-view divs are\n" +
  "// appended into .route-stage on DOMContentLoaded.\n" +
  "(function () {\n" +
  "  var VIEWS = " + JSON.stringify(ordered) + ";\n" +
  "  var html = '';\n" +
  "  for (var i = 0; i < VIEWS.length; i++) {\n" +
  "    var v = VIEWS[i];\n" +
  "    if (v === 'route' || v === 'radar' || v === 'loom' || v === 'rhythm' || v === 'rings' || v === 'quota') continue;\n" +
  "    html += '<link rel=\"stylesheet\" href=\"assets/views/' + v + '.css\">' +\n" +
  "            '<script src=\"assets/views/' + v + '.js\"><\\/script>';\n" +
  "  }\n" +
  "  document.write(html);\n" +
  "  window.ObservatoryManifest = VIEWS;\n" +
  "})();\n" +
  "\n" +
  "/* stage-view placeholders: appended into .route-stage on DOMContentLoaded.\n" +
  "   Each view id in the manifest gets one empty .stage-view div — modules\n" +
  "   register renderers that fill it on demand. */\n" +
  "(function () {\n" +
  "  function seed() {\n" +
  "    var stage = document.querySelector('.route-stage');\n" +
  "    if (!stage) return;\n" +
  "    (window.ObservatoryManifest || []).forEach(function (v) {\n" +
  "      if (v === 'route' || document.getElementById('view-' + v)) return;\n" +
  "      var d = document.createElement('div');\n" +
  "      d.className = 'stage-view';\n" +
  "      d.id = 'view-' + v;\n" +
  "      d.hidden = true;\n" +
  "      stage.appendChild(d);\n" +
  "    });\n" +
  "  }\n" +
  "  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', seed);\n" +
  "  else seed();\n" +
  "})();\n";
writeFileSync(join(root, "public/assets/views/manifest.js"), manifest);

// --- regenerate docs/views-catalog.md ------------------------------------------
const total = rows.length;
let doc = `# Magpie Observatory · 视图图鉴 (${total})\n\n`;
doc += "按分组列出每个视图的名称、eyebrow 与一句话描述。视图目录由 `public/assets/app.js` 的 `VIEW_META` 维护；\n";
doc += "运行时 `window.ObservatoryManifest` + `document.write` 自动加载 `views/*.js/.css`。\n\n";
doc += "| 分组 | 数量 |\n|---|---|\n";
for (const g of groups) doc += `| ${g} | ${byGroup[g].length} |\n`;
doc += "\n---\n";
for (const g of groups) {
  doc += `\n## ${g} (${byGroup[g].length})\n\n`;
  doc += "| id | 标题 | eyebrow | 说明 | 预览 |\n|---|---|---|---|---|\n";
  for (const r of byGroup[g]) {
    const shot = existsSync(join(root, `public/shots/${r.id}.png`)) ? `![${r.id}](../public/shots/${r.id}.png)` : "—";
    doc += `| \`${r.id}\` | ${r.title} | ${r.eyebrow} | ${r.hint} | ${shot} |\n`;
  }
}
writeFileSync(join(root, "docs/views-catalog.md"), doc);

// --- sanity report --------------------------------------------------------------
const missingFiles = ids.filter(id => !viewFilesSet.has(id));
const orphanFiles = [...viewFilesSet].filter(v => !metaSet.has(v));
if (missingFiles.length) {
  console.warn("missing view files:", missingFiles.join(", "));
}
if (orphanFiles.length) {
  console.warn("orphan view files (not in VIEW_META):", orphanFiles.join(", "));
}

console.log(`synced ${ordered.length} view files / ${total} meta rows → manifest.js + views-catalog.md`);
